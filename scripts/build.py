#!/usr/bin/env python3
"""把手写源 + 采集源合并去重 → 生成各客户端产物，并更新 data/counts.json。

用法：
  python3 scripts/build.py                # 全部类目
  python3 scripts/build.py --only light   # 只重建轻量类目（日更）
  python3 scripts/build.py --only heavy   # 只重建重类目（周更）

产物：dist/{surge,loon,quantumultx,clash,egern}/ + dist/sing-box/*.json
"""
import argparse
import datetime
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "sources"
AUTO = SRC / "auto"
DIST = ROOT / "dist"
DATA = ROOT / "data"
COUNTS = DATA / "counts.json"
CFG = ROOT / "upstreams.yml"

KINDS = ("DOMAIN-SUFFIX", "DOMAIN", "DOMAIN-KEYWORD",
         "DOMAIN-REGEX", "DOMAIN-WILDCARD", "URL-REGEX", "IP-CIDR", "IP-CIDR6")
DOM_KINDS = ("DOMAIN-SUFFIX", "DOMAIN", "DOMAIN-KEYWORD")
QX = {"DOMAIN-SUFFIX": "HOST-SUFFIX", "DOMAIN": "HOST", "DOMAIN-KEYWORD": "HOST-KEYWORD",
      "IP-CIDR": "IP-CIDR", "IP-CIDR6": "IP6-CIDR"}
EGERN_KEY = {"DOMAIN-SUFFIX": "domain_suffix_set", "DOMAIN": "domain_set",
             "DOMAIN-KEYWORD": "domain_keyword_set", "DOMAIN-REGEX": "domain_regex_set",
             "DOMAIN-WILDCARD": "domain_wildcard_set", "URL-REGEX": "url_regex_set",
             "IP-CIDR": "ip_cidr_set", "IP-CIDR6": "ip_cidr6_set"}
SINGBOX_KEY = {"DOMAIN-SUFFIX": "domain_suffix", "DOMAIN": "domain",
               "DOMAIN-KEYWORD": "domain_keyword", "IP-CIDR": "ip_cidr", "IP-CIDR6": "ip_cidr"}
FATAL_TLDS = {"com", "net", "org"}


def wc2re(w):
    """glob 通配符转正则：* -> .*，其余字符转义并锚定"""
    return "^" + re.escape(w).replace(r"\*", ".*") + "$"


def parse(path, sink, bad):
    if not path.exists():
        return
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = [p.strip() for p in line.split(",")]
        kind, value, opts = parts[0].upper(), (parts[1] if len(parts) > 1 else ""), parts[2:]
        if kind not in sink or not value:
            bad.append((path.name, line))
            continue
        if kind.startswith("IP-"):
            v = value.strip()
            sink[kind][v] = sink[kind].get(v, False) or ("no-resolve" in opts)
        elif kind in ("DOMAIN-REGEX", "URL-REGEX", "DOMAIN-WILDCARD"):
            sink[kind].add(value.strip())
        else:
            sink[kind].add(value.lower())


def title_of(path, fallback):
    if not path.exists():
        return fallback
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip().startswith("#"):
            return line.lstrip("# ").strip()
        if line.strip():
            break
    return fallback


def ip_lines(rules):
    for kind in ("IP-CIDR", "IP-CIDR6"):
        for v, nr in sorted(rules[kind].items()):
            yield kind, v, nr


def dangerous(name, rules):
    errs = []
    for v in rules["DOMAIN-SUFFIX"]:
        if v in FATAL_TLDS:
            errs.append(f"{name}: DOMAIN-SUFFIX,{v}（顶级域，会把整个 .{v} 劫持到该策略）")
    for v in rules["DOMAIN-KEYWORD"]:
        if len(v) < 3:
            errs.append(f"{name}: DOMAIN-KEYWORD,{v}（太短，误伤风险高）")
    for _, v, _ in ip_lines(rules):
        if "/" not in v:
            errs.append(f"{name}: IP-CIDR,{v}（缺少掩码）")
    return errs


def single_labels(rules):
    out = sorted(v for v in rules["DOMAIN-SUFFIX"] if "." not in v)
    out += sorted(v for v in rules["DOMAIN"] if "." not in v)
    return out


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def emit(name, title, rules):
    head = [f"# {title}", "# generated by scripts/build.py — 改 sources/ 或 upstreams.yml", ""]

    ip = [(k, v, nr) for k, v, nr in ip_lines(rules)]
    ip_txt = [f"{k},{v}{',no-resolve' if nr else ''}" for k, v, nr in ip]
    dom_txt = [f"{k},{v}" for k in DOM_KINDS for v in sorted(rules[k])]
    re_txt = [f"DOMAIN-REGEX,{v}" for v in sorted(rules["DOMAIN-REGEX"])]
    wc_txt = [f"DOMAIN-WILDCARD,{v}" for v in sorted(rules["DOMAIN-WILDCARD"])]
    url_txt = [f"URL-REGEX,{v}" for v in sorted(rules["URL-REGEX"])]
    wc_as_re = [f"DOMAIN-REGEX,{wc2re(v)}" for v in sorted(rules["DOMAIN-WILDCARD"])]
    all_txt = dom_txt + re_txt + wc_txt + url_txt + ip_txt

    # Surge
    lines = list(head) + all_txt
    write(DIST / "surge" / f"{name}.list", "\n".join(lines) + "\n")

    # Loon
    lines = list(head) + all_txt
    write(DIST / "loon" / f"{name}.list", "\n".join(lines) + "\n")

    # Quantumult X
    lines = list(head) + ([f"{QX[k]},{v}" for k in DOM_KINDS for v in sorted(rules[k])]
                          + [f"URL-REGEX,{v}" for v in sorted(rules["URL-REGEX"])]
                          + [f"{QX[k]},{v}{',no-resolve' if nr else ''}" for k, v, nr in ip_lines(rules)])
    write(DIST / "quantumultx" / f"{name}.list", "\n".join(lines) + "\n")

    # Clash / Mihomo / Stash
    body = ([f"  - {x}" for x in dom_txt] + [f"  - {x}" for x in re_txt]
            + [f"  - {x}" for x in wc_as_re] + [f"  - {x}" for x in ip_txt])
    write(DIST / "clash" / f"{name}.yaml",
          f"# {title}\n# generated by scripts/build.py\npayload:\n" + "\n".join(body) + "\n")

    # Egern 原生
    parts = list(head)
    for k in KINDS:
        vals = sorted(rules[k])
        if not vals:
            continue
        parts.append(f"{EGERN_KEY[k]}:")
        parts += [f"  - {v}" for v in vals]
        parts.append("")
    write(DIST / "egern" / f"{name}.yaml", "\n".join(parts))

    # sing-box rule-set（source JSON，version 1）
    rule = {}
    for k in DOM_KINDS:
        vals = sorted(rules[k])
        if vals:
            rule[SINGBOX_KEY[k]] = vals
    rex = sorted(set(rules["DOMAIN-REGEX"]) | {wc2re(v) for v in rules["DOMAIN-WILDCARD"]})
    if rex:
        rule["domain_regex"] = rex
    ips = sorted({v for _, v, _ in ip_lines(rules)})
    if ips:
        rule["ip_cidr"] = ips
    doc = {"version": 1, "rules": [rule] if rule else []}
    write(DIST / "sing-box" / f"{name}.json",
          json.dumps(doc, ensure_ascii=False, separators=(",", ":")) + "\n")


def heavy_flags():
    try:
        import yaml
        cfgs = yaml.safe_load(CFG.read_text(encoding="utf-8")) or {}
        return {n for n, c in cfgs.items() if (c or {}).get("heavy")}
    except Exception:  # noqa: BLE001
        return set()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", choices=["all", "light", "heavy"], default="all")
    args = ap.parse_args()

    heavy = heavy_flags()
    names = sorted({p.stem for p in SRC.glob("*.txt")} | {p.stem for p in AUTO.glob("*.txt")})
    if args.only == "light":
        names = [n for n in names if n not in heavy]
    elif args.only == "heavy":
        names = [n for n in names if n in heavy]
    if not names:
        sys.exit("没有匹配的类目")

    old = json.loads(COUNTS.read_text(encoding="utf-8")) if COUNTS.exists() else {"categories": {}}
    counts = old.get("categories", {})
    warnings = {}
    bad_lines, errors = [], []
    for name in names:
        rules = {k: ({} if k.startswith("IP-") else set()) for k in KINDS}  # IP 用 dict，其余 set
        manual, auto = SRC / f"{name}.txt", AUTO / f"{name}.txt"
        parse(manual, rules, bad_lines)
        parse(auto, rules, bad_lines)
        errors += dangerous(name, rules)
        sl = single_labels(rules)
        if sl:
            warnings[name] = {"count": len(sl), "sample": sl[:15]}
        title = title_of(manual, title_of(auto, name))
        emit(name, title, rules)
        by_kind = {k: len(v) for k, v in rules.items() if v}
        counts[name] = {"entries": sum(by_kind.values()), "by_kind": by_kind, "title": title,
                        "heavy": name in heavy,
                        "has_manual": manual.exists(), "has_auto": auto.exists(),
                        "origin": "manual+auto" if manual.exists() and auto.exists()
                                  else ("manual" if manual.exists() else "auto")}
        print(f"  {name:<16} {counts[name]['entries']:>7} 条 -> 6 个客户端")

    if warnings:
        (DATA / "warnings.json").write_text(json.dumps(warnings, ensure_ascii=False, indent=2),
                                            encoding="utf-8")
    if bad_lines:
        print(f"  ! 跳过 {len(bad_lines)} 行无法解析（首条: {bad_lines[0]}）", file=sys.stderr)
    if errors:
        print("\n危险规则检查失败:", file=sys.stderr)
        for e in errors:
            print("  ✗", e, file=sys.stderr)
        sys.exit(1)

    DATA.mkdir(parents=True, exist_ok=True)
    COUNTS.write_text(json.dumps({
        "generated_at": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "categories": dict(sorted(counts.items()))}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8")
    print(f"重建 {len(names)} 个类目 · 全库 {len(counts)} 个 · "
          f"{sum(c['entries'] for c in counts.values())} 条规则")


if __name__ == "__main__":
    main()
