#!/usr/bin/env python3
"""把手写源 + 采集源合并去重 → 生成各客户端产物到 dist/，并写 data/counts.json。

模型（参考 VPSDance/ai-proxy-rules）：
  sources/<name>.txt        手写白名单（长期有效，上游挂了也不会丢）
  sources/auto/<name>.txt   每天从上游聚合
  两者合并去重 = 该类目的最终规则
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "sources"
AUTO = SRC / "auto"
DIST = ROOT / "dist"
COUNTS = ROOT / "data" / "counts.json"

KINDS = ("DOMAIN-SUFFIX", "DOMAIN", "DOMAIN-KEYWORD", "IP-CIDR", "IP-CIDR6")
QX = {"DOMAIN-SUFFIX": "HOST-SUFFIX", "DOMAIN": "HOST", "DOMAIN-KEYWORD": "HOST-KEYWORD",
      "IP-CIDR": "IP-CIDR", "IP-CIDR6": "IP6-CIDR"}
EGERN_KEY = {"DOMAIN-SUFFIX": "domain_suffix_set", "DOMAIN": "domain_set",
             "DOMAIN-KEYWORD": "domain_keyword_set", "IP-CIDR": "ip_cidr_set",
             "IP-CIDR6": "ip_cidr6_set"}


def parse(path, sink, bad):
    if not path.exists():
        return
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = [p.strip() for p in line.split(",")]
        kind, value, opts = parts[0].upper(), (parts[1] if len(parts) > 1 else ""), parts[2:]
        if kind not in sink or not value:
            bad.append((path.name, line))
            continue
        item = value if kind.startswith("IP-") else value.lower()
        if kind.startswith("IP-") and "no-resolve" in opts:
            item += ",no-resolve"
        sink[kind].add(item)


def title_of(path, fallback):
    if not path.exists():
        return fallback
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip().startswith("#"):
            return line.lstrip("# ").strip()
        if line.strip():
            break
    return fallback


FATAL_TLDS = {"com", "net", "org"}


def dangerous(name, rules):
    """真正会劫持大量流量的规则才算失败；其余单标签条目记为 warning（上游噪音）"""
    errs = []
    for v in rules["DOMAIN-SUFFIX"]:
        if v in FATAL_TLDS:
            errs.append(f"{name}: DOMAIN-SUFFIX,{v}（顶级域，会把整个 .{v} 劫持到该策略）")
    for v in rules["DOMAIN-KEYWORD"]:
        if len(v) < 3:
            errs.append(f"{name}: DOMAIN-KEYWORD,{v}（太短，误伤风险高）")
    for v in list(rules["IP-CIDR"]) + list(rules["IP-CIDR6"]):
        if "/" not in v:
            errs.append(f"{name}: IP-CIDR,{v}（缺少掩码）")
    return errs


def single_labels(rules):
    """单标签条目（不含点）：多为上游噪音，LAN 类目里的 local/home 是正常的"""
    out = sorted(v for v in rules["DOMAIN-SUFFIX"] if "." not in v)
    out += sorted(v for v in rules["DOMAIN"] if "." not in v)
    return out


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def emit(name, title, rules):
    head = [f"# {title}", "# generated by scripts/build.py — 改 sources/ 或 upstreams.yml", ""]

    lines = list(head)
    for k in KINDS:
        lines += [f"{k},{v}" for v in sorted(rules[k])]
    write(DIST / "surge" / f"{name}.list", "\n".join(lines) + "\n")

    lines = list(head)
    for k in KINDS:
        lines += [f"{QX[k]},{v}" for v in sorted(rules[k])]
    write(DIST / "quantumultx" / f"{name}.list", "\n".join(lines) + "\n")

    body = [f"  - {k},{v}" for k in KINDS for v in sorted(rules[k])]
    write(DIST / "clash" / f"{name}.yaml",
          f"# {title}\n# generated by scripts/build.py\npayload:\n" + "\n".join(body) + "\n")

    parts = list(head)
    for k in KINDS:
        vals = sorted(rules[k])
        if not vals:
            continue
        parts.append(f"{EGERN_KEY[k]}:")
        parts += [f"  - {v}" for v in vals]
        parts.append("")
    write(DIST / "egern" / f"{name}.yaml", "\n".join(parts))


def main():
    names = sorted({p.stem for p in SRC.glob("*.txt")} | {p.stem for p in AUTO.glob("*.txt")})
    if not names:
        sys.exit("sources/ 为空")
    bad_lines, errors, counts, warnings = [], [], {}, {}
    for name in names:
        rules = {k: set() for k in KINDS}
        manual, auto = SRC / f"{name}.txt", AUTO / f"{name}.txt"
        parse(manual, rules, bad_lines)
        parse(auto, rules, bad_lines)
        errs = dangerous(name, rules)
        errors += errs
        sl = single_labels(rules)
        if sl:
            warnings[name] = {"count": len(sl), "sample": sl[:15]}
        title = title_of(manual, title_of(auto, name))
        emit(name, title, rules)
        by_kind = {k: len(v) for k, v in rules.items() if v}
        counts[name] = {"entries": sum(by_kind.values()), "by_kind": by_kind,
                        "title": title,
                        "origin": "manual" if manual.exists() else "auto",
                        "has_manual": manual.exists(), "has_auto": auto.exists()}
        print(f"  {name:<16} {counts[name]['entries']:>7} 条 -> 4 个客户端")
    if bad_lines:
        print(f"  ! 跳过 {len(bad_lines)} 行无法解析的规则（首条: {bad_lines[0]}）", file=sys.stderr)
    if errors:
        print("\n危险规则检查失败:", file=sys.stderr)
        for e in errors:
            print("  ✗", e, file=sys.stderr)
        sys.exit(1)
    if warnings:
        print("  ! 单标签条目（上游噪音，已保留但建议清理上游）:", file=sys.stderr)
        for k, v in sorted(warnings.items(), key=lambda kv: -kv[1]["count"]):
            print(f"      {k:<14} {v['count']:>4} 条  例: {', '.join(v['sample'][:6])}", file=sys.stderr)
        (COUNTS.parent / "warnings.json").write_text(
            json.dumps(warnings, ensure_ascii=False, indent=2), encoding="utf-8")
    COUNTS.parent.mkdir(parents=True, exist_ok=True)
    COUNTS.write_text(json.dumps({"generated_at": __import__("datetime").datetime.now(
        __import__("datetime").timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "categories": counts}, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"共 {len(names)} 个规则集，{sum(c['entries'] for c in counts.values())} 条规则")


if __name__ == "__main__":
    main()
