#!/usr/bin/env python3
"""把 sources/ 下的单一源（Surge 语法）生成各客户端产物到 dist/。

源格式：每行 `DOMAIN-SUFFIX,x` / `DOMAIN,x` / `DOMAIN-KEYWORD,x` / `IP-CIDR,x[,no-resolve]` / `IP-CIDR6,...`
`#` 开头为注释。产物：surge / quantumultx / clash / egern。
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "sources"
DIST = ROOT / "dist"

KINDS = ("DOMAIN-SUFFIX", "DOMAIN", "DOMAIN-KEYWORD", "IP-CIDR", "IP-CIDR6")
QX = {"DOMAIN-SUFFIX": "HOST-SUFFIX", "DOMAIN": "HOST", "DOMAIN-KEYWORD": "HOST-KEYWORD",
      "IP-CIDR": "IP-CIDR", "IP-CIDR6": "IP6-CIDR"}


def parse(path):
    out = {k: [] for k in KINDS}
    warn = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = [p.strip() for p in line.split(",")]
        kind, value, opts = parts[0].upper(), (parts[1] if len(parts) > 1 else ""), parts[2:]
        if kind not in out or not value:
            warn.append(line)
            continue
        item = value if kind.startswith("IP-") else value.lower()
        if kind.startswith("IP-") and "no-resolve" in opts:
            item += ",no-resolve"
        if item not in out[kind]:
            out[kind].append(item)
    if warn:
        print(f"  ! {path.name}: 跳过 {len(warn)} 行不支持/无法解析的规则", file=sys.stderr)
    return out


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def build(name, rules, title):
    made = []

    # Surge / Loon / Egern 都能直接吃这种 .list
    lines = [f"# {title}", "# generated by scripts/build.py — 请改 sources/ 不要改这里", ""]
    for k in KINDS:
        lines += [f"{k},{v}" for v in sorted(rules[k])]
    made.append(write(DIST / "surge" / f"{name}.list", "\n".join(lines) + "\n"))

    # Quantumult X
    lines = [f"# {title}", "# generated by scripts/build.py", ""]
    for k in KINDS:
        lines += [f"{QX[k]},{v}" for v in sorted(rules[k])]
    made.append(write(DIST / "quantumultx" / f"{name}.list", "\n".join(lines) + "\n"))

    # Clash / Mihomo（classical rule-provider）
    body = []
    for k in KINDS:
        body += [f"  - {k},{v}" for v in sorted(rules[k])]
    made.append(write(DIST / "clash" / f"{name}.yaml",
                      f"# {title}\n# generated by scripts/build.py\npayload:\n" + "\n".join(body) + "\n"))

    # Egern 原生 YAML
    key = {"DOMAIN-SUFFIX": "domain_suffix_set", "DOMAIN": "domain_set",
           "DOMAIN-KEYWORD": "domain_keyword_set", "IP-CIDR": "ip_cidr_set",
           "IP-CIDR6": "ip_cidr6_set"}
    parts = [f"# {title}", "# generated by scripts/build.py", ""]
    for k in KINDS:
        vals = sorted(rules[k])
        if not vals:
            continue
        parts.append(f"{key[k]}:")
        parts += [f"  - {v}" for v in vals]
        parts.append("")
    made.append(write(DIST / "egern" / f"{name}.yaml", "\n".join(parts)))
    return made


def main():
    files = sorted(SRC.glob("*.txt")) + sorted((SRC / "auto").glob("*.txt"))
    if not files:
        sys.exit("sources/ 为空")
    total = 0
    for f in files:
        rules = parse(f)
        title = next((l.lstrip("# ").strip() for l in f.read_text(encoding="utf-8").splitlines()
                      if l.strip().startswith("#")), f.stem)
        made = build(f.stem, rules, title)
        n = sum(len(v) for v in rules.values())
        total += n
        print(f"  {f.stem:<20} {n:>4} 条 -> {len(made)} 个客户端")
    print(f"共 {len(files)} 个规则集，{total} 条规则")


if __name__ == "__main__":
    main()
